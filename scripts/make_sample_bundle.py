"""Generate examples/sample_bundle from the project's own fixture app (never from a real target).

Usage:  python scripts/make_sample_bundle.py
The bundle contains only redacted artifacts; the script verifies that no fixture secret appears in it.
"""
from __future__ import annotations

import asyncio
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "src")]

from tests import fixture_app as fx  # noqa: E402
from webaudit.config import BodyPolicy, CrawlLimits, ScanConfig  # noqa: E402
from webaudit.scan import run_scan  # noqa: E402

INCLUDE = ["scan_metadata.json", "manifest.json", "coverage.json", "findings.json", "report.md", "pages.jsonl", "endpoints.jsonl",
           "requests.jsonl", "network_events.jsonl"]


async def _noop(url: str) -> None:
    return None


async def main() -> None:
    server = await fx.FixtureServer().start()
    tmp = Path(tempfile.mkdtemp())
    cfg = ScanConfig(initial_url=server.main_url + "/sec", confirm_authorized=True, allow_http_local=True, headless=True,
                     extra_allowed_origins=[server.api_url], output_dir=str(tmp / "out"), profile_dir=str(tmp / "profile"),
                     body=BodyPolicy(mode="selected"),
                     crawl=CrawlLimits(max_pages=10, max_depth=2, request_delay_ms=0, settle_ms=400, max_interactions_per_page=2))
    scan_dir = await run_scan(cfg, login_prompt=_noop)
    await server.stop()
    dest = ROOT / "examples" / "sample_bundle"
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for name in INCLUDE:
        shutil.copy2(scan_dir / name, dest / name)
    shutil.copytree(scan_dir / "bodies", dest / "bodies")
    (dest / "README.md").write_text(
        "# Sample sanitized audit bundle\n\nGenerated by `scripts/make_sample_bundle.py` from the project's local fixture application "
        "(not a real target). All sensitive values are redacted; the fixture's planted secrets do not appear anywhere in this directory. "
        "Ports, ids and timestamps differ between runs. Machine-specific paths were replaced with `<local>` after export, so the "
        "checksums in manifest.json describe the original export, not these edited copies.\n", encoding="utf-8")
    # strip machine-specific paths (temp dirs, user name) from the copied text files
    for p in dest.rglob("*"):
        if p.is_file():
            t = p.read_text(encoding="utf-8", errors="replace")
            for needle in sorted({str(tmp), str(tmp).replace("\\", "\\\\"), tmp.as_posix(), str(Path.home()), str(Path.home()).replace("\\", "\\\\")}, key=len, reverse=True):
                t = t.replace(needle, "<local>")
            p.write_text(t, encoding="utf-8")
    secrets = [fx.SECRET_JWT, fx.SECRET_AWS, fx.SECRET_PASSWORD, fx.SECRET_EMAIL, fx.SECRET_SSN, fx.SECRET_API_KEY,
               "FIXTURE-TOKEN-0123456789", "fixturesessionvalue123"]
    for p in dest.rglob("*"):
        if p.is_file():
            text = p.read_text(encoding="utf-8", errors="replace")
            leaked = [s for s in secrets if s in text]
            if leaked:
                raise SystemExit(f"LEAK in {p}: {leaked}")
    print(f"sample bundle written to {dest} ({sum(1 for _ in dest.rglob('*') if _.is_file())} files, no fixture secrets found)")


if __name__ == "__main__":
    asyncio.run(main())
